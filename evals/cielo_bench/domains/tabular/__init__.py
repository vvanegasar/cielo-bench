"""Tabular domain: an agent answering questions about a company's own data with SQL.

Ground truth: reference SQL on a seeded, synthetic SQLite snapshot of a fictional
mid-sized distributor (customers, products, orders, order lines, invoices, payments and
inventory), frozen and hashed. Tools: ``describe_schema`` and ``run_sql`` (read-only).
Design: ``docs/DOMAINS.md`` (section "Tabular (enterprise data)") and ADR-0006.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from ...config import FIXTURES_DIR, GOLDEN_DIR, PROJECT_ROOT
from ...domain import Domain, Evidence, ToolEvent
from .evidence import read_evidence
from .generate import file_sha256, manifest, write_database
from .schema import DB_FILENAME, MANIFEST_FILENAME
from .templates import AS_OF_PHRASE, TEMPLATES
from .tools import FAULT_PROFILES, TOOL_SPECS, TabularToolExecutor

PREAMBLE = {
    "en": (
        "You are a data assistant for a mid-sized wholesale distributor of beverages, food, cleaning, "
        "personal-care and paper products. You answer questions about the company's own records: "
        "customers, orders, invoices, payments and inventory. The company's data is a snapshot "
        f"{AS_OF_PHRASE['en']} (end of day). Amounts are in US dollars, excluding taxes. Periods are calendar "
        "months and quarters (Q1 = January to March)."
    ),
    "es": (
        "Eres un asistente de datos de una distribuidora mayorista mediana de bebidas, alimentos y productos "
        "de aseo, cuidado personal y papelería. Respondes preguntas sobre los registros de la propia empresa: "
        "clientes, pedidos, facturas, pagos e inventario. Los datos de la empresa son una foto "
        f"{AS_OF_PHRASE['es']} (al cierre del día). Los montos están en dólares estadounidenses, sin impuestos. "
        "Los periodos son meses y trimestres calendario (el primer trimestre va de enero a marzo)."
    ),
}
VALUE_EXAMPLES = {"en": ("$1,234,567.89", "42"), "es": ("1 234 567,89 dólares", "42")}
CREDIT = (
    "Synthetic data generated by cielo-bench (seeded and deterministic). The company, its customers, "
    "products and figures are fictional; any resemblance to a real business is coincidental."
)


class TabularDomain(Domain):
    name = "tabular"
    title = "Tabular enterprise data: a fictional distributor's sales, invoices, payments and inventory (read-only SQL)"
    credits = (CREDIT,)
    fault_profiles = FAULT_PROFILES
    default_fault_profile = "error"
    external_source = False  # a local, synthetic snapshot: nothing outside the machine

    def __init__(self, fixtures_dir: Path | None = None, golden_path: Path | None = None):
        self.fixtures_dir = fixtures_dir or FIXTURES_DIR / "tabular"
        self._golden_path = golden_path or GOLDEN_DIR / "tabular-v1" / "golden.json"
        self._replay_cache: dict[str, dict[str, Any]] = {}
        self._info: dict[str, Any] | None = None

    # ---- the snapshot -----------------------------------------------------------------
    @property
    def db_path(self) -> Path:
        return self.fixtures_dir / DB_FILENAME

    @property
    def manifest_path(self) -> Path:
        return self.fixtures_dir / MANIFEST_FILENAME

    @property
    def db_relpath(self) -> str:
        try:
            return str(self.db_path.resolve().relative_to(PROJECT_ROOT))
        except ValueError:
            return str(self.db_path)

    def write_manifest(self) -> dict[str, Any]:
        data = manifest(self.db_path)
        self.manifest_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        self._info = data
        return data

    def database_info(self) -> dict[str, Any]:
        """The snapshot's manifest, after checking the file against it (once per instance)."""
        if self._info is None:
            self._info = self._load_info()
        return self._info

    def _load_info(self) -> dict[str, Any]:
        if not self.db_path.is_file():  # a missing snapshot is regenerated from its seed
            write_database(self.db_path)
            return self.write_manifest()
        if not self.manifest_path.is_file():
            return self.write_manifest()
        data = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        if file_sha256(self.db_path) != data.get("file_sha256"):
            raise RuntimeError(
                f"{self.db_path} does not match its manifest (file_sha256). The snapshot was modified; "
                "rebuild it with `cielo-bench --domain tabular build-golden`."
            )
        return data

    @property
    def golden_path(self) -> Path:
        return self._golden_path

    # ---- 1. item generator ------------------------------------------------------------
    def build_golden(
        self, *, offline: bool = False, max_requests: int | None = None, settings: Mapping[str, str] | None = None
    ) -> dict[str, Any]:
        from .build import build_golden

        return build_golden(self, offline=offline, max_requests=max_requests, settings=settings)

    def verify_golden(self, golden: Any) -> list[str]:
        from .build import verify_golden

        return verify_golden(self, golden)

    # ---- 2. tools ---------------------------------------------------------------------
    def system_preamble(self, lang: str) -> str:
        return PREAMBLE[lang]

    def value_examples(self, lang: str) -> tuple[str, ...]:
        return VALUE_EXAMPLES[lang]

    def tool_specs(self) -> list[dict[str, Any]]:
        return TOOL_SPECS

    def make_executor(
        self,
        *,
        fault_profile: str | None = None,
        offline: bool = True,
        max_live_requests: int | None = None,
        settings: Mapping[str, str] | None = None,
    ) -> TabularToolExecutor:
        del offline, max_live_requests, settings  # local snapshot: nothing is fetched
        info = self.database_info()
        return TabularToolExecutor(self.db_path, content_sha256=info["content_sha256"], fault_profile=fault_profile)

    # ---- 3. ground truth and tolerances ------------------------------------------------
    def premise_holds(self, pair: Mapping[str, Any], premise_value: Any, facts: Mapping[str, Any]) -> bool | None:
        template = TEMPLATES[pair["template"]]
        return template.premise_holds(premise_value, dict(facts), dict(pair["context"]))

    # ---- 4. evidence ------------------------------------------------------------------
    def replay(self, arguments: dict[str, Any]) -> dict[str, Any]:
        """Run a trial's ``run_sql`` arguments again, read-only, on the healthy snapshot (cached)."""
        key = json.dumps(arguments, sort_keys=True, ensure_ascii=False, default=str)
        if key not in self._replay_cache:
            if len(self._replay_cache) > 4096:
                self._replay_cache.clear()
            self._replay_cache[key] = self.make_executor().execute("run_sql", arguments)
        return self._replay_cache[key]

    def evidence(self, pair: Mapping[str, Any], trace: list[ToolEvent]) -> Evidence:
        template = TEMPLATES[pair["template"]]
        specs = template.fact_specs(dict(pair["facts"]), dict(pair["context"]))
        attempted, obtained, facts = read_evidence(specs, trace, self.replay)
        return Evidence(attempted=attempted, obtained=obtained, facts=facts)

    def value_from_facts(self, pair: Mapping[str, Any], facts: Mapping[str, Any]) -> float | None:
        template = TEMPLATES[pair["template"]]
        return template.value_from_facts(dict(facts), dict(pair["context"]))

    def perturb_call(self, call: Mapping[str, Any]) -> dict[str, Any] | None:
        from .perturb import perturb_sql

        sql = (call.get("args") or {}).get("sql")
        wrong = perturb_sql(sql) if isinstance(sql, str) else None
        return None if wrong is None else {"tool": call["tool"], "args": {"sql": wrong}}


__all__ = ["TabularDomain"]
